export interface IllustratedAsset {
  symbol: string
  color: string
  label?: string
  url?: string
}

export const ADVANCED_ASSETS = new Map<string, IllustratedAsset>()

function asset(id: string, symbol: string, label: string, color = '#eef7f4') {
  ADVANCED_ASSETS.set(id, { symbol, label, color })
  return id
}

function everyday(
  id: string,
  topic: EverydayTopic,
  narration: string,
  preferred: [string, string, string],
  other: [string, string, string],
  explanation: string,
  difficulty: KidsDifficulty = 1,
  third?: [string, string, string],
): EverydayScenario {
  const choices = [preferred, other, ...(third ? [third] : [])].map(
    ([choiceId, symbol, label]) => ({
      id: `${id}-${choiceId}`,
      assetId: asset(`${id}-${choiceId}-asset`, symbol, label),
      narration: label,
    }),
  )
  return {
    id,
    topic,
    narration,
    choices,
    preferredChoiceId: choices[0]!.id,
    explanationNarration: explanation,
    difficulty,
    enabled: true,
    origin: 'SYSTEM',
  }
}

