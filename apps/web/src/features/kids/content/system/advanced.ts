const emotionIcons: Record<EmotionType, string> = {
  HAPPY: '🙂',
  SAD: '😢',
  ANGRY: '😠',
  SCARED: '😨',
  SURPRISED: '😮',
  TIRED: '😴',
}

function emotion(
  id: string,
  scene: string,
  narration: string,
  expected: EmotionType,
  alternatives: EmotionType[],
  explanation: string,
  difficulty: KidsDifficulty = 1,
): EmotionScenario {
  return {
    id,
    sceneAssetId: asset(`${id}-scene`, scene, narration, '#fff2d9'),
    narration,
    options: [expected, ...alternatives],
    expectedEmotion: expected,
    explanationNarration: explanation,
    difficulty,
    enabled: true,
    origin: 'SYSTEM',
  }
}

