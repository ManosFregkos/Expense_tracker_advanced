function sequence(
  id: string,
  title: string,
  icons: string[],
  labels: string[],
  category: string,
  difficulty: KidsDifficulty = 1,
): SequenceDefinition {
  return {
    id,
    title,
    steps: icons.map((symbol, index) => ({
      id: `${id}-step-${index + 1}`,
      assetId: asset(`${id}-asset-${index + 1}`, symbol, labels[index]!),
      narration: labels[index]!,
    })),
    narration: 'Τι έρχεται μετά;',
    explanationNarration: `Πρώτα ${labels[0]}, μετά ${labels[1]}, και στο τέλος ${labels.at(-1)}.`,
    difficulty,
    category,
    enabled: true,
    origin: 'SYSTEM',
  }
}

